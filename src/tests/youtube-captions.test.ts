import {expect,it,vi} from 'vitest';
import {captionFormatUrls,extractCaptionMetadata,fetchYouTubeCaptions,parseCaptionBody} from '../../server/youtubeCaptions';
const videoId='abcdefghijk';
const caption={baseUrl:'https://www.youtube.com/api/timedtext?v='+videoId+'&sig=original&fmt=srv3',vssId:'.en',languageCode:'en',name:{runs:[{text:'English [CC]'}]}};
const watch=(tracks:unknown[])=>'var ytInitialPlayerResponse = '+JSON.stringify({videoDetails:{videoId},playabilityStatus:{status:'OK'},captions:{playerCaptionsTracklistRenderer:{captionTracks:tracks}}})+';';
it('parses complete caption metadata containing nested arrays and quoted brackets',()=>{
 expect(extractCaptionMetadata(watch([caption]),videoId).tracks).toEqual([caption]);
 expect(()=>extractCaptionMetadata(watch([caption]),'otherVid123')).toThrow('different video');
});
it('preserves signed parameters and replaces fmt instead of duplicating it',()=>{
 const urls=captionFormatUrls(caption.baseUrl);
 expect(urls[0]).toBe(caption.baseUrl);
 for(const value of urls){const url=new URL(value);expect(url.searchParams.get('sig')).toBe('original');expect(url.searchParams.getAll('fmt')).toHaveLength(1);}
 for(const value of ['http://www.youtube.com/api/timedtext','https://evil.example/api/timedtext','https://www.youtube.com/watch?v=x'])expect(()=>captionFormatUrls(value)).toThrow('address');
});
it('converts JSON3, XML and VTT captions without claiming word timing',()=>{
 expect(parseCaptionBody(JSON.stringify({events:[{tStartMs:1250,segs:[{utf8:'Hello '},{utf8:'world'}]}]}))).toBe('[00:01.25]Hello world');
 expect(parseCaptionBody('<transcript><text start="2.5">A &amp; B</text></transcript>')).toBe('[00:02.50]A & B');
 expect(parseCaptionBody('WEBVTT\n\n00:00:02.500 --> 00:00:04.000\nA caption')).toBe('[00:02.50]A caption');
});
it('retrieves captions directly with the same authenticated request and labels automatic tracks',async()=>{
 const automatic={...caption,vssId:'a.en',kind:'asr'};
 const request=vi.fn(async(input:RequestInfo|URL,init?:RequestInit)=>{
  expect((init?.headers as Record<string,string>).Cookie).toBe('session=fixture');
  return String(input).includes('/watch?')?new Response(watch([automatic])):new Response('<transcript><text start="1">Original test text</text></transcript>');
 });
 const result=await fetchYouTubeCaptions(videoId,{headers:{Cookie:'session=fixture'},request:request as typeof fetch});
 expect(result?.subtitleTracks[0]).toMatchObject({isAutoGenerated:true,label:'English [CC] (auto-generated)'});
 expect(result?.hasWordSync).toBe(false);
 expect(request).toHaveBeenCalledTimes(2);
});
it('distinguishes missing caption tracks from blocked requests and never tries random proxies',async()=>{
 const missing=vi.fn(async()=>new Response(watch([])));
 expect(await fetchYouTubeCaptions(videoId,{request:missing})).toBeNull();
 const blocked=vi.fn(async()=>new Response('',{status:403}));
 await expect(fetchYouTubeCaptions(videoId,{request:blocked})).rejects.toMatchObject({code:'restricted'});
 expect(blocked).toHaveBeenCalledTimes(1);
});
it('moves to the next format when a signed caption URL returns an empty response',async()=>{
 const request=vi.fn(async(input:RequestInfo|URL)=>String(input).includes('/watch?')?new Response(watch([caption])):new Response(new URL(String(input)).searchParams.get('fmt')==='json3'?JSON.stringify({events:[{tStartMs:0,segs:[{utf8:'Original test phrase'}]}]}):''));
 expect((await fetchYouTubeCaptions(videoId,{request:request as typeof fetch}))?.lrc).toBe('[00:00.00]Original test phrase');
});
it('cancels network work when an external advertisement replaces the song',async()=>{
 const controller=new AbortController();
 const request=vi.fn((_input:RequestInfo|URL,init?:RequestInit)=>new Promise<Response>((_,reject)=>init?.signal?.addEventListener('abort',()=>reject(init.signal?.reason),{once:true})));
 const pending=fetchYouTubeCaptions(videoId,{signal:controller.signal,request:request as typeof fetch});
 controller.abort(new DOMException('Advertisement','AbortError'));
 await expect(pending).rejects.toMatchObject({name:'AbortError'});
});
