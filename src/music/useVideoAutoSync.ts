import {useEffect,useMemo,useState} from 'react';
import {fetchYouTubeSubtitlesForTrack} from '../lyrics/appleLyrics';
import {computeVideoDelayFromSubtitles,type YouTubeSubtitleTrackItem} from '../lyrics/lyricFlowEngine';
import {computeLeadingNonMusicOffset,fetchSponsorBlockSegments} from './sponsorBlock';

/** Song lyrics remain authoritative. Only the muted video's timeline is shifted. */
export function useVideoAutoSync(key:string,videoId:string|null,enabled:boolean,lyrics:string,lyricPresentationShift=0){
 const [state,setState]=useState<{key:string;tracks:YouTubeSubtitleTrackItem[];intro:number;captionStatus:string;pending:boolean}>({key:'',tracks:[],intro:0,captionStatus:'',pending:false});
 useEffect(()=>{
  if(!enabled||!videoId)return;
  const controller=new AbortController();
  setState({key,tracks:[],intro:0,captionStatus:'Checking creator video subtitles for timing…',pending:true});
  const update=(patch:Partial<typeof state>)=>{if(!controller.signal.aborted)setState(previous=>previous.key===key?{...previous,...patch}:previous);};
  // Publish independently: a slow SponsorBlock response must not hold up usable captions.
  void fetchYouTubeSubtitlesForTrack(videoId,controller.signal).then(result=>{
   const tracks=(result?.subtitleTracks||[]).filter(track=>!track.isAutoGenerated&&!/^a\./i.test(track.id)&&!/auto[ -]generated|asr/i.test(track.label));
   update({tracks,pending:false,captionStatus:tracks.length?`Creator subtitles available: ${tracks.map(t=>t.label).join(', ')}`:result?'Only automatic captions are available; they are excluded from video sync.':'No accessible creator captions. Using SponsorBlock intro timing when available.'});
  }).catch(error=>update({tracks:[],pending:false,captionStatus:error instanceof Error?error.message:'Video subtitles are unavailable. Using SponsorBlock when available.'}));
  void fetchSponsorBlockSegments(videoId,controller.signal).then(segments=>update({intro:computeLeadingNonMusicOffset(segments)})).catch(()=>{});
  return()=>controller.abort();
 },[key,videoId,enabled]);
 const current=enabled&&videoId&&state.key===key?state:null;
 return useMemo(()=>{
  if(!enabled||!videoId)return {delaySeconds:0,status:'',captionStatus:''};
  const match=lyrics&&current?.tracks.length?computeVideoDelayFromSubtitles(lyrics,current.tracks):null;
  if(match?.matched){
   const delaySeconds=Number(Math.max(-300,Math.min(300,match.videoDelaySeconds+lyricPresentationShift)).toFixed(2));
   return {delaySeconds,status:`Synced via creator YT subtitles (${match.languageCode||'same language'} · ${match.anchorCount} anchors · ${delaySeconds>0?'+':''}${delaySeconds}s)`,captionStatus:current?.captionStatus||''};
  }
  const intro=current?.intro||0;
  return {delaySeconds:-intro,status:intro>.25?`Cut ${intro.toFixed(1)}s leading non-music intro via SponsorBlock`:current?.pending?'Checking creator subtitles · manual video delay is available':'Direct start (0s offset · adjust manual video delay if needed)',captionStatus:current?.captionStatus||''};
 },[current,enabled,videoId,lyrics,lyricPresentationShift]);
}
