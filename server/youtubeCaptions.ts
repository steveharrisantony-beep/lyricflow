import { fetchYouTubeSubtitles, parseYouTubeSubtitles, YouTubeSubtitleError } from './youtubeSubtitles';

/** Direct caption requests with verified TLS, one deadline and no public proxy pools. */
export interface CaptionTrack {
  baseUrl:string; languageCode?:string; kind?:string; vssId?:string;
  name?:{simpleText?:string;runs?:Array<{text?:string}>};
}
export interface CaptionResult {
  lrc:string; source:string; sourceUrl:string; hasWordSync:false;
  subtitleTracks:Array<{id:string;languageCode:string;label:string;lrc:string;lineCount:number;isAutoGenerated:boolean}>;
}
export class CaptionFetchError extends Error {
  constructor(message:string,public readonly code:'restricted'|'unavailable'|'timeout'|'invalid-response') {super(message);}
}

/** Read a complete JSON object/array, including nested arrays and quoted brackets. */
export function readBalancedJson(text:string,start:number):unknown {
  const open=text[start],close=open==='{'?'}':open==='['?']':'';
  if(!close)return null;
  const stack:string[]=[];let quoted=false,escape=false;
  for(let i=start;i<text.length;i++){
    const c=text[i];
    if(quoted){if(escape)escape=false;else if(c==='\\')escape=true;else if(c==='"')quoted=false;continue;}
    if(c==='"'){quoted=true;continue;}
    if(c==='{'||c==='[')stack.push(c==='{'?'}':']');
    else if(c==='}'||c===']'){
      if(stack.pop()!==c)return null;
      if(!stack.length){try{return JSON.parse(text.slice(start,i+1));}catch{return null;}}
    }
  }
  return null;
}
export function extractCaptionMetadata(html:string,videoId:string):{tracks:CaptionTrack[];status:string;recognized:boolean}{
  let response:Record<string,unknown>|null=null;
  const assignment=/(?:ytInitialPlayerResponse\s*=|"ytInitialPlayerResponse"\s*:)\s*/g;
  for(const match of html.matchAll(assignment)){
    const value=readBalancedJson(html,match.index!+match[0].length);
    if(value&&typeof value==='object'&&!Array.isArray(value)){response=value as Record<string,unknown>;break;}
  }
  if(response){
    const details=response.videoDetails as {videoId?:string}|undefined;
    if(details?.videoId&&details.videoId!==videoId)throw new CaptionFetchError('YouTube returned captions for a different video.','invalid-response');
    const captions=response.captions as {playerCaptionsTracklistRenderer?:{captionTracks?:CaptionTrack[]}}|undefined;
    const playback=response.playabilityStatus as {status?:string}|undefined;
    return {tracks:captions?.playerCaptionsTracklistRenderer?.captionTracks||[],status:playback?.status||'UNKNOWN',recognized:true};
  }
  // Some watch pages serialize only the caption list in their initial data.
  const match=/"captionTracks"\s*:\s*/.exec(html);
  const value=match?readBalancedJson(html,match.index+match[0].length):null;
  return {tracks:Array.isArray(value)?value as CaptionTrack[]:[],status:'UNKNOWN',recognized:Array.isArray(value)};
}
